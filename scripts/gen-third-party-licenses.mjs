#!/usr/bin/env node
/* Generate THIRD-PARTY-LICENSES.md from the vendored trees and their reports.
 *
 *   node scripts/gen-third-party-licenses.mjs          # writes the file
 *   node scripts/gen-third-party-licenses.mjs --check  # fails if it is stale
 *
 * One row per directory under code/: upstream URL, pin and licence as recorded
 * in codebase-reports/<codebase>/codebase-metadata.json, plus the licence files
 * found at the top of the vendored tree. Generated, never hand-edited: the
 * vendored trees and the reports are the truth, this file is their projection.
 * It never adds a licence file to a vendored tree — a tree stays byte-identical
 * to its pin, and a codebase whose upstream ships no licence file is listed as
 * such, with the status its report records.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CODE = path.join(ROOT, 'code');
const REPORTS = path.join(ROOT, 'codebase-reports');
const OUT = path.join(ROOT, 'THIRD-PARTY-LICENSES.md');

const check = process.argv.includes('--check');
const licenseFileRe = /(licen[sc]e|copying|copyright|notice|unlicense)/i;
const cell = (v) => String(v).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

const rows = [];
const missing = [];
for (const name of fs.readdirSync(CODE).sort()) {
  const dir = path.join(CODE, name);
  if (!fs.statSync(dir).isDirectory()) continue;
  const metaPath = path.join(REPORTS, name, 'codebase-metadata.json');
  const meta = fs.existsSync(metaPath) ? JSON.parse(fs.readFileSync(metaPath, 'utf8')).codebase ?? {} : {};
  const files = fs
    .readdirSync(dir)
    .filter((f) => licenseFileRe.test(f) && fs.statSync(path.join(dir, f)).isFile())
    .sort();
  const bundled = (meta.agent_authored?.bundled_licenses ?? []).map(
    (b) => `${b.component} is ${b.license}`,
  );
  const recorded = meta.license && meta.license !== 'None' ? meta.license : 'No repository-wide licence recorded';
  rows.push({
    name,
    url: meta.upstream_url ?? '',
    pin: meta.upstream_pin ?? '',
    license: bundled.length ? `${recorded}; ${bundled.join('; ')}` : recorded,
    files,
  });
  if (files.length === 0) missing.push(name);
}

const lines = [
  '# Third-party licences',
  '',
  '<!-- Generated by scripts/gen-third-party-licenses.mjs. Do not edit by hand. -->',
  '',
  'Every directory under `code/` is a legacy scientific codebase vendored at the upstream pin below. Each remains under its own licence; the root `LICENSE` covers only the benchmark\'s own material. The licence column is what the codebase report records, and the last column lists the licence files at the top of the vendored tree.',
  '',
  'Vendored trees are kept byte-identical to their pins, so no licence file is added to a tree whose upstream ships none. Those codebases are listed under the table.',
  '',
  '| Codebase | Upstream | Pin | Licence | Licence files in `code/<codebase>/` |',
  '|---|---|---|---|---|',
  ...rows.map(
    (r) =>
      `| \`${r.name}\` | ${cell(r.url)} | \`${cell(r.pin)}\` | ${cell(r.license)} | ${
        r.files.length ? r.files.map((f) => `\`${f}\``).join(', ') : 'none upstream'
      } |`,
  ),
  '',
  '## Codebases with no top-level licence file',
  '',
  'Upstream ships no top-level licence file at the pin for these. The licence column above is the full recorded status; `codebase-reports/<codebase>/` holds the evidence.',
  '',
  ...missing.map((n) => `- \`${n}\``),
  '',
];
const text = lines.join('\n');

if (check) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== text) {
    console.error('THIRD-PARTY-LICENSES.md is stale: run node scripts/gen-third-party-licenses.mjs');
    process.exit(1);
  }
  console.log(`THIRD-PARTY-LICENSES.md is current (${rows.length} codebases)`);
} else {
  fs.writeFileSync(OUT, text);
  console.log(`wrote THIRD-PARTY-LICENSES.md (${rows.length} codebases, ${missing.length} without a top-level licence file)`);
}
